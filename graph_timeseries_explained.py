# =====================================================================
# 1本ごとの時系列グラフ【解説付き版】
# ---------------------------------------------------------------------
# このプログラムがやること（全体の流れ）
#   1. Excelファイルを開いて、15ロット分の数字を読み込む
#   2. ロットごとに「実測値の折れ線」「基準線」「上限・下限線」を描く
#   3. 15枚の小さなグラフを1枚の大きな画像（PNG）に並べて保存する
#
# プログラムは基本的に「上から下へ、1行ずつ順番に」実行されます。
# 「#」で始まる行は“コメント”で、人間へのメモ。Pythonは無視します。
# =====================================================================


# ---------------------------------------------------------------------
# 【1】道具を借りてくる（import）
# ---------------------------------------------------------------------
# Pythonは単体だと計算ぐらいしかできません。グラフを描く・Excelを読むといった
# 得意な仕事は、他の人が作った“部品集（ライブラリ）”を借りて行います。
# 「import ○○ as △△」は「○○を借りて、以降は△△という短い名前で呼ぶ」の意味です。

import numpy as np                  # numpy: 数字の表（配列）を高速に計算する道具。npと略す
import matplotlib                   # matplotlib: グラフを描く道具の本体
matplotlib.use("Agg")               # 「画面には出さず、画像ファイルとして保存するモード」にする
import matplotlib.pyplot as plt     # matplotlibの中の“描画係”。pltと略す（グラフ作りの主役）
from openpyxl import load_workbook  # openpyxl: Excelを読む道具。その中の「load_workbook」だけ借りる


# ---------------------------------------------------------------------
# 【2】設定（変数）
# ---------------------------------------------------------------------
# 「名前 = 値」は“変数”です。値に名前を付けて箱にしまっておくイメージ。
# 後で何度も使う数字や文字をここにまとめておくと、直すときに1か所で済みます。
# 文字は "" で囲みます（これを“文字列”と呼ぶ）。数字は囲みません。

EXCEL_FILE = "新規_Microsoft_Excel_ワークシート.xlsx"   # 読み込むExcelのファイル名
OUT_FILE = "全ロット_1本ごとの時系列.png"               # 保存する画像のファイル名
N_LOTS = 15          # ロットの数
FIRST_ROW = 5        # データが始まるExcelの行番号（5行目から）
FIRST_COL = 1        # ロット1の「実測値」の列。★Pythonは0から数える★ので A列=0, B列=1, C列=2…
COLS_PER_LOT = 4     # 1ロットが使う列数（実測値・基準・上限・下限の4列）
FONT_NAME = "Hiragino Sans"   # グラフに使う日本語フォント（Macの標準フォント）

# グラフ全体の「標準の設定」を書き換える。
# rcParams は“グラフの初期設定の一覧表”で、辞書（キーと値のセット）になっています。
plt.rcParams["font.family"] = FONT_NAME      # 文字のフォントを日本語対応のものにする（これが無いと文字化け）
plt.rcParams["axes.unicode_minus"] = False   # マイナス記号が□にならないようにする保険


# ---------------------------------------------------------------------
# 【3】Excelを読み込む
# ---------------------------------------------------------------------
# data_only=True … セルに数式が入っている場合、数式ではなく“計算結果の値”を読む指定。
# .active … 最初に開かれるシート（ワークシート）のこと。
ws = load_workbook(EXCEL_FILE, data_only=True).active

# iter_rows … シートを1行ずつ順に取り出す命令。min_row=5 で「5行目から」。
# values_only=True … セルの“値だけ”欲しい（書式などは要らない）という指定。
# list(...) … 取り出した行を「リスト」（順番に並んだ入れ物）にまとめる。
# これで rows[0] が5行目、rows[1] が6行目…という具合に、行ごとのデータが入ります。
# さらに rows[0][1] と書くと「5行目のB列の値」を指します（[行][列]の順）。
rows = list(ws.iter_rows(min_row=FIRST_ROW, values_only=True))


# ---------------------------------------------------------------------
# 【4】「数字かどうか」を判定する小さな道具（関数）
# ---------------------------------------------------------------------
# “関数”＝名前を付けた小さな作業手順。「def 名前(受け取るもの):」で作ります。
# 一度作っておけば、あとで is_num(値) と書くだけで何度でも呼び出せます。
# isinstance(v, (int, float)) は「vは整数または小数ですか？」という質問で、
# 答えは True（はい）か False（いいえ）。#N/A や空欄は数字ではないので False になります。
def is_num(v):
    return isinstance(v, (int, float))   # return … 答えを呼び出し元へ返す


# ---------------------------------------------------------------------
# 【5】大きな画像（キャンバス）を用意する
# ---------------------------------------------------------------------
COLS = 3                                   # 横に並べるグラフの数（3列）
NR = int(np.ceil(N_LOTS / COLS))           # 縦に何段必要か。15÷3=5段。
                                           #   np.ceil は“切り上げ”（16ロットなら 5.33→6段）
                                           #   int(...) は小数を整数に直す
H = 3.9 * NR + 1.8                         # 画像の高さ（インチ）。段数が増えたら高くする。
                                           #   1.8 は上のタイトル用の余白

# figure … 画像全体（白い紙）。figsize=(幅, 高さ)、dpi=解像度（大きいほど細かい）
fig = plt.figure(figsize=(18, H), dpi=130)

# gridspec … 紙の上に「NR行 × COLS列」の升目を引く。
# left/right/top/bottom … 紙の端からどれだけ空けるか（0〜1の割合）
# hspace/wspace … 升目どうしの縦・横のすき間
gs = fig.add_gridspec(NR, COLS, left=0.045, right=0.915, top=1 - 1.7 / H,
                      bottom=0.04, hspace=0.40, wspace=0.42)


# ---------------------------------------------------------------------
# 【6】ロットごとにグラフを描く（繰り返し処理 for）
# ---------------------------------------------------------------------
# 「for k in range(15):」は「kを 0,1,2,…,14 と変えながら、下の字下げした部分を15回繰り返す」。
# Pythonは字下げ（行頭の空白）で“繰り返しの範囲”を表します。字下げが揃っている間が1回分の処理。
# k=0 がロット1、k=1 がロット2…に対応します。

for k in range(N_LOTS):

    # --- (a) このロットのデータをExcelの表から切り出す ---------------------
    # ロットkの「実測値」の列番号。ロット1(k=0)ならB列(1)、ロット2(k=1)なら1+4=5列目…
    c = FIRST_COL + COLS_PER_LOT * k

    # 少し長い1行ですが、分解するとこうです。
    #   for r in rows                    … 行を1つずつ r として取り出す
    #   if all(is_num(r[c+j]) for j in range(4))
    #                                     … その行の4列（実測値・基準・上限・下限）が
    #                                       「すべて数字」なら採用（#N/Aや空欄の行は捨てる）
    #   r[c:c+4]                         … 行rの c列目から4つ分を切り出す（[開始:終了]のスライス。終了は含まない）
    #   [ ... ]                          … 採用した行を並べて1つの表（リストのリスト）にする
    #   np.array(..., float)             … それをnumpyの数字の表（配列）に変換。floatは“小数として扱う”指定
    # 結果 d は「行=1本ごとの測定、列=[実測値, 基準, 上限, 下限]」の表になります。
    d = np.array([r[c:c + 4] for r in rows if all(is_num(r[c + j]) for j in range(4))], float)

    y = d[:, 0]    # d[:, 0] は「全部の行の、0番目の列」＝実測値だけを取り出す（: は“全部”の意味）

    # d[0, 1] は「0行目(先頭)の、1番目の列」。基準・上限・下限は全行同じ値なので先頭行から1つ取る。
    # 「a, b, c = x, y, z」と書くと、3つの変数に一度に代入できます。
    base, upper, lower = d[0, 1], d[0, 2], d[0, 3]
    n = len(y)     # len … 要素の数。つまりこのロットで測った本数

    # --- (b) 升目の中に、このロット用のグラフ枠を作る -----------------------
    # k // COLS は“割り算の商”（何段目か）、k % COLS は“割り算の余り”（何列目か）。
    # 例: k=4 → 4//3=1段目(0始まり)、4%3=1列目。こうして左上から順に並べます。
    ax = fig.add_subplot(gs[k // COLS, k % COLS])   # ax＝この1枚のグラフ（座標軸）

    # --- (c) 線を描く ---------------------------------------------------
    # plot(横の値, 縦の値) … 折れ線を描く。横は 1,2,3,…n の番号（np.arange(1, n+1)で作る）。
    # color=色コード、lw=線の太さ(line width)
    ax.plot(np.arange(1, n + 1), y, color="#78909c", lw=.6)   # 灰色の細い線＝実測値

    # axhline … 「水平(horizontal)な線」を指定の高さに1本引く。ls="--" は破線。
    ax.axhline(base, color="#1565c0", lw=2.2)                  # 青い実線＝基準
    ax.axhline(upper, color="#d32f2f", lw=2, ls="--")          # 赤い破線＝上限
    ax.axhline(lower, color="#d32f2f", lw=2, ls="--")          # 赤い破線＝下限

    # --- (d) 線の右端に「上限 295.8」のようなラベルを付ける -----------------
    # 3つのラベルを同じ手順で付けたいので、3組の(高さ, 文字, 色)をまとめて繰り返します。
    # f"上限 {upper:.1f}" は“f文字列”：{ }の中に変数の値を埋め込める文字列。
    #   「:.1f」は「小数点以下1桁で表示」の指定（295.84 → 295.8）。
    for v, t, col in ((upper, f"上限 {upper:.1f}", "#d32f2f"),
                      (base,  f"基準 {base:.1f}",  "#1565c0"),
                      (lower, f"下限 {lower:.1f}", "#d32f2f")):
        # text(x位置, y位置, 文字, ...) … 好きな場所に文字を置く。
        # x=1.0 は“グラフ枠の右端”、y=v は“データの値の高さ”（transformでそう読み替えている）。
        # va="center" 縦は線の真ん中に合わせる / ha="left" 横は左揃えで外側へ伸ばす
        # clip_on=False … 枠の外にはみ出しても消さない（右の余白に文字を出すため）
        ax.text(1.0, v, t, transform=ax.get_yaxis_transform(), color=col,
                fontsize=11, va="center", ha="left", clip_on=False)

    # --- (e) 縦軸・横軸の範囲や見た目を整える -------------------------------
    # グラフの縦の範囲：実測値と上下限のうち、一番低い値(lo)と一番高い値(hi)を求める。
    # min(…, …) / max(…, …) は小さい方 / 大きい方を返す関数。
    lo, hi = min(y.min(), lower), max(y.max(), upper)
    # 上下に15%＋0.5gの余白を足して表示範囲にする（線が枠にくっつかないように）
    ax.set_ylim(lo - 0.15 * (hi - lo) - 0.5, hi + 0.15 * (hi - lo) + 0.5)
    ax.set_xlim(0, n + 20)                                   # 横の範囲：0〜(本数+少し)
    ax.yaxis.set_major_locator(plt.MaxNLocator(5, integer=True))  # 縦の目盛りは最大5個、整数の位置に
    ax.grid(axis="y", color="#ececec", lw=.8)                # 横方向の薄いガイド線を引く
    ax.set_axisbelow(True)                                   # ガイド線をデータ線の後ろに回す
    for s in ("top", "right"):                               # 枠線のうち「上」「右」を
        ax.spines[s].set_visible(False)                      # 非表示にしてすっきりさせる

    # --- (f) タイトルと軸の名前 ---------------------------------------------
    ax.set_title(f"ロット{k + 1}", loc="left", fontsize=17, fontweight="bold", pad=8)
    #   k は0始まりなので k+1 を表示（ロット1,2,3…）。loc="left"で左寄せ、padは枠との距離。

    # if 条件: … 「条件が成り立つときだけ」字下げした行を実行する。
    if k % COLS == 0:                        # 余りが0＝一番左の列のグラフだけ
        ax.set_ylabel("製品の重さ (g)", fontsize=11)   # 縦軸の名前を付ける（毎回付けるとうるさいので）
    if k + COLS >= N_LOTS:                   # 一番下の段のグラフだけ
        ax.set_xlabel("測定順（本）", fontsize=12)      # 横軸の名前を付ける


# ---------------------------------------------------------------------
# 【7】全体のタイトルを付けて、画像として保存
# ---------------------------------------------------------------------
# for文の字下げが終わった（行頭に戻った）ので、ここからは15回の繰り返しの“後”の処理です。

# suptitle … 図全体の見出し。yは縦位置（1が一番上）。
fig.suptitle("各ロットの時系列（基準値＝開始時5個の平均、上下限 ±1.4 g）",
             fontsize=24, fontweight="bold", y=1 - 0.25 / H)

# fig.text(x, y, 文字) … 図の好きな位置（0〜1の割合）に文字を置く。0.5は真ん中。
fig.text(0.5, 1 - 0.85 / H, "灰色の線＝1本ごとの実測値　／　青い線＝基準値　／　赤い破線＝上限・下限",
         ha="center", fontsize=13, color="#555")

fig.savefig(OUT_FILE, dpi=130)       # 画像ファイルとして保存（ここで初めてPNGができる）
print("保存しました:", OUT_FILE)       # 画面にメッセージを表示（動作確認用）


