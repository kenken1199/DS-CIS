# =====================================================================
# ケース単位の推移グラフ【解説付き版】
# ---------------------------------------------------------------------
# このプログラムがやること（全体の流れ）
#   1. Excelファイルを開いて、15ロット分の「ケースごとの平均・最小・最大・はね本数」を読み込む
#   2. ロットごとに
#        ・濃い線　 ＝ ケースごとの平均
#        ・水色の帯 ＝ そのケースの中の最小〜最大
#        ・赤い棒　 ＝ はねた本数（右側の目盛り）
#      を重ねて描く
#   3. 15枚の小さなグラフを1枚の大きな画像（PNG）に並べて保存する
#
# プログラムは基本的に「上から下へ、1行ずつ順番に」実行されます。
# 「#」で始まる行は“コメント”で、人間へのメモ。Pythonは無視します。
# =====================================================================


# ---------------------------------------------------------------------
# 【1】道具を借りてくる（import）
# ---------------------------------------------------------------------
# Pythonは単体だと計算ぐらいしかできません。グラフを描く・Excelを読むといった
# 得意な仕事は、他の人が作った“部品集（ライブラリ）”を借りて行います。
# 「import ○○ as △△」は「○○を借りて、以降は△△という短い名前で呼ぶ」の意味です。

import numpy as np                  # numpy: 数字の表（配列）を高速に計算する道具。npと略す
import matplotlib                   # matplotlib: グラフを描く道具の本体
matplotlib.use("Agg")               # 「画面には出さず、画像ファイルとして保存するモード」にする
import matplotlib.pyplot as plt     # matplotlibの中の“描画係”。pltと略す（グラフ作りの主役）
from openpyxl import load_workbook  # openpyxl: Excelを読む道具。その中の「load_workbook」だけ借りる


# ---------------------------------------------------------------------
# 【2】設定（変数）
# ---------------------------------------------------------------------
# 「名前 = 値」は“変数”です。値に名前を付けて箱にしまっておくイメージ。
# 後で何度も使う数字や文字をここにまとめておくと、直すときに1か所で済みます。
# 文字は "" で囲みます（これを“文字列”と呼ぶ）。数字は囲みません。

EXCEL_FILE = "Book1.xlsx"                      # 読み込むExcelのファイル名
OUT_FILE = "全ロット_ケース単位の推移.png"      # 保存する画像のファイル名
N_LOTS = 15          # ロットの数
FIRST_ROW = 5        # 1ケース目のデータがあるExcelの行番号（5行目から）
LAST_ROW = 37        # 最後のケースの行番号（37行目まで）
FIRST_COL = 1        # ロット1の「平均」の列。★Pythonは0から数える★ので A列=0, B列=1, C列=2…
COLS_PER_LOT = 4     # 1ロットが使う列数（平均・最小・最大・はね本数の4列）
FONT_NAME = "Hiragino Sans"   # グラフに使う日本語フォント（Macの標準フォント）

# グラフ全体の「標準の設定」を書き換える。
# rcParams は“グラフの初期設定の一覧表”で、辞書（キーと値のセット）になっています。
plt.rcParams["font.family"] = FONT_NAME      # 文字のフォントを日本語対応のものにする（これが無いと文字化け）
plt.rcParams["axes.unicode_minus"] = False   # マイナス記号が□にならないようにする保険


# ---------------------------------------------------------------------
# 【3】Excelを読み込む
# ---------------------------------------------------------------------
# data_only=True … セルに数式が入っている場合、数式ではなく“計算結果の値”を読む指定。
# .active … 最初に開かれるシート（ワークシート）のこと。
ws = load_workbook(EXCEL_FILE, data_only=True).active

# iter_rows … シートを1行ずつ順に取り出す命令。5行目〜37行目だけを対象にする。
# values_only=True … セルの“値だけ”欲しい（書式などは要らない）という指定。
# list(...) … 取り出した行を「リスト」（順番に並んだ入れ物）にまとめる。
# これで rows[0] が5行目、rows[1] が6行目…という具合に、行ごとのデータが入ります。
# さらに rows[0][1] と書くと「5行目のB列の値」を指します（[行][列]の順）。
rows = list(ws.iter_rows(min_row=FIRST_ROW, max_row=LAST_ROW, values_only=True))


# ---------------------------------------------------------------------
# 【4】ロットごとのデータを取り出して、リストにためておく（for ループ）
# ---------------------------------------------------------------------
# 空っぽのリストを作る。ここに15ロット分のデータを1つずつ追加していきます。
lots = []

# 「for k in range(15):」は「kを 0,1,2,…,14 と変えながら、下の字下げした部分を15回繰り返す」。
# Pythonは字下げ（行頭の空白）で“繰り返しの範囲”を表します。字下げが揃っている間が1回分の処理。
# k=0 がロット1、k=1 がロット2…に対応します。
for k in range(N_LOTS):
    # ロットkの「平均」の列番号。ロット1(k=0)ならB列(1)、ロット2(k=1)なら1+4=5列目…
    c = FIRST_COL + COLS_PER_LOT * k

    # 分解するとこうです。
    #   for r in rows        … 行を1つずつ r として取り出す
    #   if r[c] is not None  … その行の「平均」が空欄でなければ採用（ケースが無い行は捨てる）
    #   r[c:c+4]             … 行rの c列目から4つ分（平均・最小・最大・はね本数）を切り出す
    #                           [開始:終了]を“スライス”と呼び、終了は含まない
    #   [ ... ]              … 採用した行を並べて1つの表にする
    #   np.array(..., float) … numpyの数字の表（配列）に変換。floatは“小数として扱う”指定
    # 結果 d は「行=1ケース、列=[平均, 最小, 最大, はね本数]」の表になります。
    d = np.array([r[c:c + 4] for r in rows if r[c] is not None], float)

    lots.append(d)   # append … リストの末尾に追加する。15回繰り返すと lots に15ロット分が入る


# ---------------------------------------------------------------------
# 【5】大きな画像（キャンバス）を用意する
# ---------------------------------------------------------------------
COLS = 3                                   # 横に並べるグラフの数（3列）
NR = int(np.ceil(N_LOTS / COLS))           # 縦に何段必要か。15÷3=5段。
                                           #   np.ceil は“切り上げ”（16ロットなら 5.33→6段）
                                           #   int(...) は小数を整数に直す
H = 4.15 * NR + 2.0                        # 画像の高さ（インチ）。段数が増えたら高くする。
                                           #   2.0 は上のタイトル用の余白

# figure … 画像全体（白い紙）。figsize=(幅, 高さ)、dpi=解像度（大きいほど細かい）
fig = plt.figure(figsize=(18, H), dpi=130)

# gridspec … 紙の上に「NR行 × COLS列」の升目を引く。
# left/right/top/bottom … 紙の端からどれだけ空けるか（0〜1の割合）
# hspace/wspace … 升目どうしの縦・横のすき間
gs = fig.add_gridspec(NR, COLS, left=0.045, right=0.955, top=1 - 1.85 / H,
                      bottom=0.035, hspace=0.62, wspace=0.30)

RIGHT_MAX = 95   # 右軸（はね本数）の上限。全ロット同じ値にして、棒の高さを見比べやすくする


# ---------------------------------------------------------------------
# 【6】ロットごとにグラフを描く（繰り返し処理 for）
# ---------------------------------------------------------------------
# enumerate(lots) … リストの中身を取り出すとき「何番目か(i)」と「中身(d)」を同時にもらえる。
# i=0,d=ロット1のデータ → i=1,d=ロット2のデータ …と15回繰り返します。
for i, d in enumerate(lots):

    # --- (a) 升目の中に、このロット用のグラフ枠を作る -----------------------
    # i // COLS は“割り算の商”（何段目か）、i % COLS は“割り算の余り”（何列目か）。
    # 例: i=4 → 4//3=1段目(0始まり)、4%3=1列目。こうして左上から順に並べます。
    ax = fig.add_subplot(gs[i // COLS, i % COLS])   # ax＝この1枚のグラフ（座標軸）

    # --- (b) データを、意味のある名前の変数に分ける -------------------------
    x = np.arange(1, len(d) + 1)    # 横軸＝ケース番号 1,2,3,…（len(d)はケース数）
    # d[:, 0] は「全部の行の、0番目の列」（: は“全部”の意味）。
    # 列は [平均, 最小, 最大, はね本数] の順なので、0〜3番目をそれぞれ取り出す。
    mean, mn, mx, rej = d[:, 0], d[:, 1], d[:, 2], d[:, 3]

    # --- (c) 水色の帯と、平均の線を描く --------------------------------------
    # fill_between(x, 下, 上) … 2本の線の間を塗りつぶす。ここでは「最小〜最大」の帯。
    #   alpha=透明度（0〜1）、lw=0 は縁取りなし、label=凡例に出す名前
    ax.fill_between(x, mn, mx, color="#90caf9", alpha=.6, lw=0, label="そのケース内の最小〜最大")
    # plot … 折れ線。"-o" は「線(-)と丸印(o)」。lw=線の太さ、ms=丸の大きさ
    # zorder … 重なり順（大きいほど手前）。帯より線を前に出す。
    ax.plot(x, mean, "-o", color="#0d47a1", lw=2.6, ms=5.5, label="ケースごとの平均", zorder=3)

    # --- (d) 縦軸・横軸の範囲や見た目を整える -------------------------------
    # 縦の範囲：帯の一番低い所(lo)と高い所(hi)を求め、その差(span)を基準に余白を決める。
    # 下側に大きめ(0.75×span)の余白を作るのは、下の方に“赤い棒”を描くスペースが欲しいから。
    lo, hi = mn.min(), mx.max()
    span = hi - lo
    ax.set_ylim(lo - 0.75 * span, hi + 0.3 * span)
    # 横の範囲：ケース数が31以上でも収まるよう、大きい方を採用（max(…, …)は大きい方を返す）
    ax.set_xlim(0, max(len(d) + 1.5, 31.5))
    ax.set_xticks([5, 10, 15, 20, 25, 30])                         # 横軸の目盛りの位置を指定
    ax.yaxis.set_major_locator(plt.MaxNLocator(5, integer=True))   # 縦の目盛りは最大5個、整数に
    ax.grid(axis="y", color="#e8e8e8", lw=.8)                      # 横方向の薄いガイド線
    ax.set_axisbelow(True)                                         # ガイド線をデータの後ろへ
    for s in ("top", "right"):                                     # 枠線の「上」「右」を
        ax.spines[s].set_visible(False)                            # 非表示にしてすっきりさせる

    # if 条件: … 「条件が成り立つときだけ」字下げした行を実行する。
    if i % COLS == 0:                          # 余りが0＝一番左の列のグラフだけ
        ax.set_ylabel("製品の重さ (g)", fontsize=11)
    if i + COLS >= N_LOTS:                     # 一番下の段のグラフだけ
        ax.set_xlabel("瓶ケースの順番（1ケース=80本）", fontsize=12)

    # --- (e) 赤い棒グラフ（はね本数）を“右軸”に重ねる -------------------------
    # 重さ(g)とはね本数(本)は単位も大きさも違うので、同じ縦軸には載せられません。
    # twinx() で「横軸は共通、縦軸だけ右側に別に持つ、もう1枚の透明なグラフ」を重ねます。
    ax2 = ax.twinx()
    ax2.bar(x, rej, color="#e57373", alpha=.45, width=.7, zorder=1)   # bar … 棒グラフ
    ax2.set_ylim(0, RIGHT_MAX)                                         # 右軸は 0〜95
    ax2.set_yticks([0, 20, 40])                                        # 目盛りは 0,20,40 だけ表示
    ax2.tick_params(axis="y", colors="#c62828")                        # 右軸の文字を赤に
    for s in ("top", "left"):
        ax2.spines[s].set_visible(False)                               # 余計な枠線を消す
    ax2.spines["right"].set_color("#c62828")                           # 右の軸線を赤に
    # 重ねた2枚のうち、平均の線がある ax を手前に出し、背景は透明にして棒が透けて見えるようにする
    ax.set_zorder(ax2.get_zorder() + 1)
    ax.patch.set_visible(False)

    # --- (f) タイトル（ロット名＋はね本数の合計）と凡例 ------------------------
    # f"…{ }…" は“f文字列”：{ }の中に変数や計算結果を埋め込める文字列。
    # rej.sum() は はね本数の合計、int(...) は小数を整数にする（7.0 → 7）。
    # i は0始まりなので i+1 を表示（ロット1,2,3…）。
    # transform=ax.transAxes は「位置を“グラフ枠の割合(0〜1)”で指定する」という意味。
    ax.text(0, 1.06, f"ロット{i + 1}　はね {int(rej.sum())}本",
            transform=ax.transAxes, fontsize=16, fontweight="bold", va="bottom")
    if i == 0:                                                         # 凡例は最初のグラフだけに表示
        ax.legend(loc="lower left", fontsize=10, framealpha=.95)       # 凡例を左下に


# ---------------------------------------------------------------------
# 【7】全体のタイトルを付けて、画像として保存
# ---------------------------------------------------------------------
# for文の字下げが終わった（行頭に戻った）ので、ここからは15回の繰り返しの“後”の処理です。

# suptitle … 図全体の見出し。yは縦位置（1が一番上）。
fig.suptitle(f"{N_LOTS}ロットのケース単位の推移", fontsize=24, fontweight="bold", y=0.993)

# fig.text(x, y, 文字) … 図の好きな位置（0〜1の割合）に文字を置く。0.5は真ん中。
fig.text(0.5, 1 - 0.95 / H,
         "濃い線＝ケースごとの平均　／　水色の帯＝そのケースの中の最小〜最大　／　赤い棒＝はねた本数（右目盛り）",
         ha="center", fontsize=12.5, color="#555")

fig.savefig(OUT_FILE, dpi=130)       # 画像ファイルとして保存（ここで初めてPNGができる）
print("保存しました:", OUT_FILE)       # 画面にメッセージを表示（動作確認用）


